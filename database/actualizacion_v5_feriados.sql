-- =====================================================================
-- HR Manager · actualización v5: feriados y tratamiento legal de los
-- francos adeudados
-- =====================================================================
--
-- Requiere la actualización v4 aplicada.
--
-- Qué trae:
--
--  1. Calendario de feriados nacionales, que se sincroniza desde una API
--     pública, de modo que un feriado agregado o movido por decreto queda
--     reflejado sin tocar el sistema. Cada empresa puede además cargar sus
--     feriados locales o de convenio.
--
--  2. Los feriados dejan de contarse como días hábiles en el cómputo del
--     artículo 151, que era la simplificación que quedaba pendiente.
--
--  3. Francos adeudados con el tratamiento del artículo 207: el franco que
--     no se otorgó en la semana siguiente puede reclamarse durante la
--     semana subsiguiente y se paga con el 100 % de recargo. Pasada esa
--     ventana el derecho caduca, de modo que el acumulado se separa en
--     reclamable y vencido en lugar de crecer para siempre.
--
--  4. Marca de recargo del 100 % sobre el franco compensatorio, para que
--     la liquidación lo tome.
--
-- Se puede ejecutar más de una vez sin efectos adversos.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. Calendario de feriados
-- ---------------------------------------------------------------------
--
-- company_id en NULL es un feriado nacional, visible para todas las
-- organizaciones. Con company_id, es un feriado propio de esa organización:
-- provincial, local o de convenio.
--
-- non_working distingue el feriado obligatorio del día no laborable. En el
-- día no laborable el empleador decide si se trabaja, así que sigue contando
-- como día hábil para el artículo 151.

CREATE TABLE IF NOT EXISTS public.public_holidays (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT REFERENCES public.companies(id) ON DELETE CASCADE,
  holiday_date DATE NOT NULL,
  name VARCHAR(160) NOT NULL,
  kind VARCHAR(24) NOT NULL DEFAULT 'inamovible'
    CHECK (kind IN ('inamovible', 'trasladable', 'puente', 'no_laborable', 'local', 'otro')),
  non_working BOOLEAN NOT NULL DEFAULT TRUE,
  source VARCHAR(40) NOT NULL DEFAULT 'manual',
  synced_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS public_holidays_nacional_uq
  ON public.public_holidays (holiday_date) WHERE company_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS public_holidays_empresa_uq
  ON public.public_holidays (company_id, holiday_date) WHERE company_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS public_holidays_date_idx
  ON public.public_holidays (holiday_date);

ALTER TABLE public.public_holidays ENABLE ROW LEVEL SECURITY;

-- Los lee cualquier usuario con sesión: los nacionales y los de su empresa.
DROP POLICY IF EXISTS "todos leen feriados" ON public.public_holidays;
CREATE POLICY "todos leen feriados" ON public.public_holidays
  FOR SELECT TO authenticated
  USING (company_id IS NULL OR company_id = (SELECT private.current_company_id()));

-- Los nacionales los administra el administrador del sistema.
DROP POLICY IF EXISTS "admin gestiona feriados nacionales" ON public.public_holidays;
CREATE POLICY "admin gestiona feriados nacionales" ON public.public_holidays
  FOR ALL TO authenticated
  USING (company_id IS NULL AND (SELECT private.is_system_admin()))
  WITH CHECK (company_id IS NULL AND (SELECT private.is_system_admin()));

-- Los propios los administra la cuenta Empresa.
DROP POLICY IF EXISTS "empresa gestiona sus feriados" ON public.public_holidays;
CREATE POLICY "empresa gestiona sus feriados" ON public.public_holidays
  FOR ALL TO authenticated
  USING (company_id = (SELECT private.current_company_id()) AND (SELECT private.is_company()))
  WITH CHECK (company_id = (SELECT private.current_company_id()) AND (SELECT private.is_company()));

-- ¿Es feriado no laborable esa fecha, para esa empresa?
CREATE OR REPLACE FUNCTION private.is_holiday(p_company_id BIGINT, p_date DATE)
RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $fn$
  SELECT EXISTS (
    SELECT 1 FROM public.public_holidays h
     WHERE h.holiday_date = p_date
       AND h.non_working
       AND (h.company_id IS NULL OR h.company_id = p_company_id)
  )
$fn$;

-- Días hábiles entre dos fechas inclusive: de lunes a viernes, descontando
-- los feriados no laborables.
CREATE OR REPLACE FUNCTION private.workdays_between(
  p_company_id BIGINT, p_from DATE, p_to DATE)
RETURNS INTEGER
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $fn$
  SELECT CASE WHEN p_to < p_from THEN 0 ELSE (
    SELECT count(*)::INTEGER
      FROM generate_series(p_from::timestamp, p_to::timestamp, INTERVAL '1 day') g
     WHERE EXTRACT(ISODOW FROM g) < 6
       AND NOT EXISTS (
         SELECT 1 FROM public.public_holidays h
          WHERE h.holiday_date = g::date
            AND h.non_working
            AND (h.company_id IS NULL OR h.company_id = p_company_id)
       )
  ) END
$fn$;

-- Feriados de un rango, para que las pantallas los marquen en el calendario.
CREATE OR REPLACE FUNCTION public.holidays_between(p_from DATE, p_to DATE)
RETURNS TABLE (holiday_date DATE, name VARCHAR, kind VARCHAR, non_working BOOLEAN, is_company BOOLEAN)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $fn$
  SELECT h.holiday_date, h.name, h.kind, h.non_working, h.company_id IS NOT NULL
    FROM public.public_holidays h
   WHERE h.holiday_date BETWEEN p_from AND p_to
     AND (h.company_id IS NULL OR h.company_id = private.current_company_id())
   ORDER BY h.holiday_date
$fn$;

-- Años cargados y cuándo se sincronizó cada uno.
CREATE OR REPLACE FUNCTION public.holiday_sync_status()
RETURNS TABLE (year INTEGER, total BIGINT, last_sync TIMESTAMPTZ, origin VARCHAR)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $fn$
  SELECT EXTRACT(YEAR FROM h.holiday_date)::INTEGER,
         count(*),
         max(h.synced_at),
         max(h.source)::VARCHAR
    FROM public.public_holidays h
   WHERE h.company_id IS NULL
   GROUP BY 1
   ORDER BY 1 DESC
$fn$;

-- Reemplaza los feriados nacionales de un año con los que trae la función de
-- servidor. Se hace en una sola transacción: o queda el año entero o no
-- cambia nada, de modo que un año no puede quedar a medias.
CREATE OR REPLACE FUNCTION public.admin_sync_holidays(p_year INTEGER, p_rows JSONB)
RETURNS INTEGER
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_total INTEGER;
BEGIN
  IF NOT private.is_system_admin() THEN
    RAISE EXCEPTION 'Solo el administrador del sistema puede sincronizar los feriados';
  END IF;
  IF p_year IS NULL OR p_year < 2000 OR p_year > 2100 THEN
    RAISE EXCEPTION 'El año indicado no es válido';
  END IF;
  IF p_rows IS NULL OR jsonb_array_length(p_rows) = 0 THEN
    RAISE EXCEPTION 'No se recibió ningún feriado para el año %', p_year;
  END IF;

  DELETE FROM public.public_holidays
   WHERE company_id IS NULL
     AND EXTRACT(YEAR FROM holiday_date)::INTEGER = p_year
     AND source <> 'manual';

  INSERT INTO public.public_holidays
    (company_id, holiday_date, name, kind, non_working, source, synced_at)
  SELECT NULL,
         (r->>'fecha')::DATE,
         left(COALESCE(NULLIF(btrim(r->>'nombre'), ''), 'Feriado'), 160),
         COALESCE(NULLIF(r->>'tipo', ''), 'otro'),
         COALESCE(NULLIF(r->>'tipo', ''), 'otro') <> 'no_laborable',
         'argentinadatos',
         CURRENT_TIMESTAMP
    FROM jsonb_array_elements(p_rows) r
   WHERE (r->>'fecha') IS NOT NULL
     AND EXTRACT(YEAR FROM (r->>'fecha')::DATE)::INTEGER = p_year
  ON CONFLICT DO NOTHING;

  GET DIAGNOSTICS v_total = ROW_COUNT;
  RETURN v_total;
END;
$fn$;

-- Feriado propio de una organización: provincial, local o de convenio.
CREATE OR REPLACE FUNCTION public.set_company_holiday(
  p_date DATE, p_name TEXT, p_non_working BOOLEAN DEFAULT TRUE)
RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_company BIGINT := private.current_company_id();
BEGIN
  IF v_company IS NULL OR NOT private.is_company() THEN
    RAISE EXCEPTION 'Solo la cuenta Empresa puede cargar feriados propios';
  END IF;
  IF p_date IS NULL OR btrim(COALESCE(p_name, '')) = '' THEN
    RAISE EXCEPTION 'Indicá la fecha y el nombre del feriado';
  END IF;

  INSERT INTO public.public_holidays
    (company_id, holiday_date, name, kind, non_working, source)
  VALUES (v_company, p_date, left(btrim(p_name), 160), 'local', p_non_working, 'manual')
  ON CONFLICT (company_id, holiday_date) WHERE company_id IS NOT NULL
  DO UPDATE SET name = EXCLUDED.name, non_working = EXCLUDED.non_working;
END;
$fn$;

CREATE OR REPLACE FUNCTION public.delete_company_holiday(p_date DATE)
RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $fn$
BEGIN
  IF NOT private.is_company() THEN
    RAISE EXCEPTION 'Solo la cuenta Empresa puede quitar sus feriados';
  END IF;
  DELETE FROM public.public_holidays
   WHERE company_id = private.current_company_id() AND holiday_date = p_date;
END;
$fn$;

-- ---------------------------------------------------------------------
-- 2. El artículo 151 pasa a descontar los feriados
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.vacation_entitlement_days(p_employee_id BIGINT, p_year INTEGER)
RETURNS INTEGER
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_emp    public.employees;
  v_cutoff DATE;
  v_start  DATE;
  v_days   INTEGER;
  v_worked INTEGER;
  v_total  INTEGER;
BEGIN
  SELECT * INTO v_emp FROM public.employees WHERE id = p_employee_id;
  IF v_emp.id IS NULL THEN RETURN 0; END IF;
  IF v_emp.id IS DISTINCT FROM private.current_employee_id()
     AND NOT private.in_scope(p_employee_id) THEN
    RAISE EXCEPTION 'No podés consultar los datos de ese empleado';
  END IF;

  v_cutoff := make_date(p_year, 12, 31);
  IF v_emp.hire_date > v_cutoff THEN RETURN 0; END IF;

  -- Artículo 150: el tramo se decide sobre la fecha exacta.
  SELECT r.entitlement_days INTO v_days
    FROM public.vacation_entitlement_ranges r
   WHERE r.company_id = v_emp.company_id
     AND (
       r.seniority_months_from = 0
       OR v_cutoff > (v_emp.hire_date + make_interval(months => r.seniority_months_from))::DATE
     )
     AND (
       r.seniority_months_to IS NULL
       OR v_cutoff <= (v_emp.hire_date + make_interval(months => r.seniority_months_to))::DATE
     )
   ORDER BY r.seniority_months_from DESC
   LIMIT 1;

  v_days := COALESCE(v_days, 0);
  IF v_days = 0 THEN RETURN 0; END IF;

  -- Artículo 151: la mitad, como mínimo, de los días hábiles del año. Los
  -- feriados no laborables no son días hábiles y quedan descontados de los
  -- dos lados de la comparación.
  v_start  := GREATEST(v_emp.hire_date, make_date(p_year, 1, 1));
  v_worked := private.workdays_between(v_emp.company_id, v_start, v_cutoff);
  v_total  := private.workdays_between(v_emp.company_id, make_date(p_year, 1, 1), v_cutoff);

  IF v_worked * 2 >= v_total THEN
    RETURN v_days;
  END IF;

  -- Artículo 153: un día de descanso por cada veinte de trabajo efectivo.
  RETURN FLOOR(v_worked / 20.0)::INTEGER;
END;
$fn$;

-- ---------------------------------------------------------------------
-- 3. Francos adeudados con el artículo 207
-- ---------------------------------------------------------------------
--
-- El artículo 207 da una ventana al descanso compensatorio que no se otorgó:
-- el trabajador puede tomarlo a partir del primer día hábil de la semana
-- subsiguiente, avisando con no menos de 24 horas, y ese día se paga con el
-- 100 % de recargo. La doctrina mayoritaria entiende que, pasada esa
-- ventana, el derecho caduca y no se acumula indefinidamente.
--
-- Como ese último punto está discutido, el sistema no lo impone: separa el
-- acumulado en reclamable y vencido, y cada organización decide con
-- days_off_backlog_expires si los vencidos siguen contando como deuda.

ALTER TABLE public.business_rules
  ADD COLUMN IF NOT EXISTS days_off_backlog_expires BOOLEAN NOT NULL DEFAULT TRUE;

-- Recargo del 100 % sobre un franco compensatorio otorgado fuera de término.
ALTER TABLE public.days_off_requests
  ADD COLUMN IF NOT EXISTS pay_surcharge BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN public.days_off_requests.pay_surcharge IS
  'Franco compensatorio otorgado fuera de término: se paga con el 100 % de recargo (artículo 207 de la Ley 20.744).';

DROP FUNCTION IF EXISTS private.days_off_backlog_row(BIGINT);
DROP FUNCTION IF EXISTS public.days_off_backlog(BIGINT);
DROP FUNCTION IF EXISTS public.days_off_backlog_all();

CREATE OR REPLACE FUNCTION private.days_off_backlog_row(p_employee_id BIGINT)
RETURNS TABLE (
  employee_id BIGINT,
  computed_from DATE,
  computed_to DATE,
  weeks_elapsed INTEGER,
  expected_days INTEGER,
  taken_days INTEGER,
  pending_days INTEGER,
  claimable_days INTEGER,
  expired_days INTEGER,
  owed_days INTEGER,
  claim_deadline DATE
)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_emp public.employees;
  v_weekly INTEGER;
  v_expires BOOLEAN;
  v_from DATE;
  v_first_monday DATE;
  v_last_sunday DATE;
  v_hoy DATE := private.today();
BEGIN
  SELECT * INTO v_emp FROM public.employees WHERE id = p_employee_id;
  IF v_emp.id IS NULL THEN RETURN; END IF;

  SELECT COALESCE(r.weekly_days_off, 0), r.days_off_backlog_from,
         COALESCE(r.days_off_backlog_expires, TRUE)
    INTO v_weekly, v_from, v_expires
    FROM public.business_rules r WHERE r.company_id = v_emp.company_id;

  v_from := GREATEST(v_emp.hire_date, COALESCE(v_from, v_emp.hire_date));

  -- Solo cuentan las semanas completas: del primer lunes en o después del
  -- inicio del cómputo, hasta el último domingo pasado.
  v_first_monday := date_trunc('week', v_from)::DATE
    + CASE WHEN v_from > date_trunc('week', v_from)::DATE THEN 7 ELSE 0 END;
  v_last_sunday := date_trunc('week', v_hoy)::DATE - 1;

  IF v_last_sunday < v_first_monday + 6 OR v_weekly = 0 THEN
    RETURN QUERY SELECT p_employee_id, v_from, v_from, 0, 0, 0, 0, 0, 0, 0, NULL::DATE;
    RETURN;
  END IF;

  RETURN QUERY
  WITH semanas AS (
    SELECT g::DATE AS lunes
      FROM generate_series(v_first_monday::timestamp,
                           (v_last_sunday - 6)::timestamp, INTERVAL '7 days') g
  ),
  otorgados AS (
    SELECT date_trunc('week', d.requested_date)::DATE AS lunes,
           count(*) FILTER (WHERE r.status = 'approved') AS aprobados,
           count(*) FILTER (WHERE r.status = 'pending')  AS pendientes
      FROM public.days_off_request_dates d
      JOIN public.days_off_requests r ON r.id = d.request_id
     WHERE r.employee_id = p_employee_id
       AND d.requested_date BETWEEN v_first_monday AND v_last_sunday
     GROUP BY 1
  ),
  detalle AS (
    SELECT s.lunes,
           v_weekly AS corresponden,
           COALESCE(o.aprobados, 0)::INTEGER AS aprobados,
           COALESCE(o.pendientes, 0)::INTEGER AS pendientes,
           GREATEST(v_weekly - COALESCE(o.aprobados, 0), 0)::INTEGER AS faltan,
           -- El descanso debía otorgarse en la semana siguiente; se puede
           -- reclamar durante la subsiguiente. Vence ese domingo.
           (s.lunes + 20) AS vence
      FROM semanas s
      LEFT JOIN otorgados o ON o.lunes = s.lunes
  )
  SELECT
    p_employee_id,
    v_first_monday,
    v_last_sunday,
    count(*)::INTEGER,
    COALESCE(sum(corresponden), 0)::INTEGER,
    COALESCE(sum(aprobados), 0)::INTEGER,
    COALESCE(sum(pendientes), 0)::INTEGER,
    COALESCE(sum(faltan) FILTER (WHERE vence >= v_hoy), 0)::INTEGER,
    COALESCE(sum(faltan) FILTER (WHERE vence <  v_hoy), 0)::INTEGER,
    CASE WHEN v_expires
         THEN COALESCE(sum(faltan) FILTER (WHERE vence >= v_hoy), 0)::INTEGER
         ELSE COALESCE(sum(faltan), 0)::INTEGER END,
    min(vence) FILTER (WHERE faltan > 0 AND vence >= v_hoy)
  FROM detalle;
END;
$fn$;

CREATE OR REPLACE FUNCTION public.days_off_backlog(p_employee_id BIGINT)
RETURNS TABLE (
  employee_id BIGINT, computed_from DATE, computed_to DATE, weeks_elapsed INTEGER,
  expected_days INTEGER, taken_days INTEGER, pending_days INTEGER,
  claimable_days INTEGER, expired_days INTEGER, owed_days INTEGER, claim_deadline DATE
)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $fn$
BEGIN
  IF p_employee_id IS DISTINCT FROM private.current_employee_id()
     AND NOT private.in_scope(p_employee_id) THEN
    RAISE EXCEPTION 'No podés consultar los datos de ese empleado';
  END IF;
  RETURN QUERY SELECT * FROM private.days_off_backlog_row(p_employee_id);
END;
$fn$;

CREATE OR REPLACE FUNCTION public.days_off_backlog_all()
RETURNS TABLE (
  employee_id BIGINT, computed_from DATE, computed_to DATE, weeks_elapsed INTEGER,
  expected_days INTEGER, taken_days INTEGER, pending_days INTEGER,
  claimable_days INTEGER, expired_days INTEGER, owed_days INTEGER, claim_deadline DATE
)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $fn$
BEGIN
  IF NOT private.is_staff() THEN
    RAISE EXCEPTION 'Solo la empresa o un encargado pueden ver el acumulado de francos';
  END IF;
  RETURN QUERY
  SELECT b.*
  FROM public.employees e
  CROSS JOIN LATERAL private.days_off_backlog_row(e.id) b
  WHERE e.id IN (SELECT unnest(private.scoped_employee_ids()))
    AND e.employment_status <> 'inactive';
END;
$fn$;

-- ---------------------------------------------------------------------
-- 4. Asignación de francos con recargo
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.assign_days_off(
  p_employee_id BIGINT,
  p_dates DATE[],
  p_reason TEXT,
  p_category VARCHAR DEFAULT 'ordinary',
  p_surcharge BOOLEAN DEFAULT FALSE
)
RETURNS public.days_off_requests
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_acc public.user_accounts;
  v_req public.days_off_requests;
BEGIN
  v_acc := private.current_account();
  IF v_acc.id IS NULL OR NOT private.is_staff() THEN
    RAISE EXCEPTION 'Solo la empresa o un encargado pueden asignar francos';
  END IF;
  IF NOT private.in_scope(p_employee_id) THEN
    RAISE EXCEPTION 'El empleado no pertenece a tu sucursal';
  END IF;
  IF p_dates IS NULL OR array_length(p_dates, 1) IS NULL THEN
    RAISE EXCEPTION 'Indicá al menos una fecha';
  END IF;
  IF EXISTS (SELECT 1 FROM unnest(p_dates) d WHERE d <= private.today()) THEN
    RAISE EXCEPTION 'Los francos se asignan desde mañana en adelante. La primera fecha posible es %.',
      to_char(private.today() + 1, 'DD/MM/YYYY');
  END IF;
  IF p_surcharge AND p_category <> 'compensatory' THEN
    RAISE EXCEPTION 'El recargo del 100 %% solo corresponde a un franco compensatorio';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.days_off_request_dates d
    JOIN public.days_off_requests r ON r.id = d.request_id
    WHERE r.employee_id = p_employee_id AND r.status IN ('pending', 'approved')
      AND d.requested_date = ANY (p_dates)
  ) THEN
    RAISE EXCEPTION 'El empleado ya tiene un franco en alguna de esas fechas';
  END IF;

  INSERT INTO public.days_off_requests (
    company_id, employee_id, submitted_by_user_id, request_type, category, reason,
    status, pay_surcharge, resolved_by_user_id, resolved_at
  ) VALUES (
    v_acc.company_id, p_employee_id, v_acc.id, 'employer_assignment', p_category, p_reason,
    'approved', COALESCE(p_surcharge, FALSE), v_acc.id, CURRENT_TIMESTAMP
  ) RETURNING * INTO v_req;

  INSERT INTO public.days_off_request_dates (company_id, request_id, requested_date)
  SELECT v_acc.company_id, v_req.id, d FROM unnest(p_dates) AS d;

  RETURN v_req;
END;
$fn$;

